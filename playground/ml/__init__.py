"""Machine-learning lab: build, train and test neural networks inside the playground.

Three layers, all measured against the physics engine rather than trusted:

  data       datasets generated by running the real MuJoCo world (playground.ml.data), or the
             throws an agent itself measured during its sessions (memory/datasets/).
  models     neural networks defined by a small JSON spec (layers, activation, inputs, target),
             trained with PyTorch (CPU, Intel XPU or CUDA) and stored with their metrics
             and baselines (playground.ml.nets, playground.ml.registry).
  testing    scoring on fresh engine data, closed-loop control (the network chooses an action,
             the engine executes it, the outcome is measured) and a neural controller that can
             be benchmarked against language-model agents (playground.ml.evaluate / controller).

PyTorch is an optional dependency (requirements-ml.txt). Everything that does not train or run a
network (dataset generation, feature extraction, the registry) works without it.
"""
from __future__ import annotations


class MLError(Exception):
    """A structured, reportable failure (bad spec, too little data, PyTorch missing...)."""

    def __init__(self, code: str, message: str, **details):
        super().__init__(message)
        self.code, self.message, self.details = code, message, details


def torch_status() -> dict:
    """Is PyTorch importable, and which accelerators does it see? Never raises."""
    try:
        import torch
    except Exception as exc:  # noqa: BLE001
        return {"available": False, "reason": f"PyTorch is not installed ({type(exc).__name__}). "
                                               "Install it with: uv pip install -r requirements-ml.txt"}
    xpu = bool(getattr(torch, "xpu", None) and torch.xpu.is_available())
    cuda = bool(torch.cuda.is_available())
    return {"available": True, "version": torch.__version__,
            "xpu": xpu, "xpu_device": torch.xpu.get_device_name(0) if xpu else None,
            "cuda": cuda, "cuda_device": torch.cuda.get_device_name(0) if cuda else None}
